"""Write compositions/captions.html from assets/vo/timing.json.

Lines whose words are already on screen (vo-01: the post itself, vo-10: the end card
tagline) are left uncaptioned. Whisper's spellings are corrected to the script's.

    python3 scripts/build_captions.py
"""
import json
import re
from pathlib import Path

P = Path(__file__).resolve().parent.parent
SKIP = {"vo-01", "vo-10"}
FIX = {
    "parody": "parity",
    "Artcraft.": "ArtCraft.",
    "Photocraft": "PhotoCraft",
    "labeled": "labelled",
    "Early": "early",
    "Alpha.": "alpha.",
    "1.": "one.",
    "2.": "two.",
    "3.": "three.",
}
MAX_WORDS = 3

timing = json.loads((P / "assets/vo/timing.json").read_text())
words = [w for w in timing["words"] if w["line"] not in SKIP]

# Script punctuation Whisper heard differently, by (line, word).
PUNCT = {("vo-07", "week,"): "week?"}

# Fix spellings, capitalise each line, and merge Whisper's split tokens ("43" ",000", "co" "-pilot.").
merged = []
for i, w in enumerate(words):
    t = PUNCT.get((w["line"], w["text"]), FIX.get(w["text"], w["text"]))
    if i == 0 or words[i - 1]["line"] != w["line"]:
        t = t[:1].upper() + t[1:]
    if merged and (t.startswith(",") or t.startswith("-")) and merged[-1]["line"] == w["line"]:
        merged[-1]["text"] += t
        merged[-1]["end"] = w["end"]
    else:
        merged.append({**w, "text": t})

groups, cur = [], []
for i, w in enumerate(merged):
    cur.append(w)
    nxt = merged[i + 1] if i + 1 < len(merged) else None
    brk = (
        len(cur) >= MAX_WORDS
        or re.search(r"[.,?!]$", w["text"])
        or nxt is None
        or nxt["line"] != w["line"]
        or nxt["start"] - w["end"] >= 0.15
    )
    if brk:
        groups.append(cur)
        cur = []

html_groups, js = [], []
for gi, g in enumerate(groups):
    start = round(g[0]["start"] - 0.05, 3)
    nxt_start = groups[gi + 1][0]["start"] - 0.05 if gi + 1 < len(groups) else 999
    end = round(min(g[-1]["end"] + 0.35, nxt_start), 3)
    spans = " ".join(f'<span id="cw{gi}-{wi}">{w["text"].rstrip(",")}</span>' for wi, w in enumerate(g))
    html_groups.append(f'      <div id="cg{gi}" class="cap-g"><div class="cap-chip">{spans}</div></div>')
    js.append(f"      group({gi}, {start}, {end}, {json.dumps([round(w['start'], 3) for w in g])});")

out = f"""<template>
  <style>
    @font-face {{ font-family: "Bricolage Grotesque"; font-weight: 200 800; font-stretch: 75% 100%; font-display: block; src: url("assets/fonts/BricolageGrotesque.woff2") format("woff2"); }}
    #root {{ position: absolute; inset: 0; pointer-events: none; }}
    .cap-g {{ position: absolute; left: 0; top: 1196px; width: 1080px; text-align: center; overflow: visible; opacity: 0; }}
    .cap-chip {{ display: inline-block; padding: 12px 26px 16px; background: #fbf6ec; border: 4px solid #1b1814; border-radius: 14px; box-shadow: 7px 7px 0 #1b1814; font-family: "Bricolage Grotesque", sans-serif; font-weight: 800; font-stretch: 75%; font-size: 74px; line-height: 1; text-transform: uppercase; color: #1b1814; white-space: nowrap; }}
  </style>
  <!-- Generated by scripts/build_captions.py — edit the script, not this file. -->
  <div id="root" data-composition-id="captions" data-width="1080" data-height="1920">
{chr(10).join(html_groups)}
  </div>
  <script>
    (() => {{
      const tl = gsap.timeline({{ paused: true }});
      const group = (i, start, end, wordStarts) => {{
        const g = `#cg${{i}}`;
        tl.fromTo(g, {{ opacity: 0, y: 10 }}, {{ opacity: 1, y: 0, duration: 0.1, ease: "power3.out" }}, start);
        wordStarts.forEach((t, w) => {{
          tl.fromTo(`#cw${{i}}-${{w}}`, {{ color: "#1b1814" }}, {{ color: "#c2502a", duration: 0.04 }}, t);
          if (w > 0) tl.to(`#cw${{i}}-${{w - 1}}`, {{ color: "#1b1814", duration: 0.04 }}, t);
        }});
        tl.to(g, {{ opacity: 0, duration: 0.08, ease: "power2.in" }}, end - 0.08);
        tl.set(g, {{ opacity: 0, visibility: "hidden" }}, end);
      }};
{chr(10).join(js)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
(P / "compositions/captions.html").write_text(out)
print(len(groups), "caption groups")
for g in groups:
    print(round(g[0]["start"], 2), " ".join(w["text"] for w in g))
