"""Write compositions/captions.html from assets/vo/timing.json.

Lines carried by big on-screen type (the re-hook, the open-weights line, the end card) are left
uncaptioned. Whisper's tokens are merged back into the script's spellings.

    python3 scripts/build_captions.py
"""
import json
import re
from pathlib import Path

P = Path(__file__).resolve().parent.parent
SKIP = {"vo-09", "vo-11", "vo-14"}
FIX = {"TerminalBench,": "Terminal-Bench,", "4th.": "fourth.", "4th,": "fourth,"}
PUNCT = {("vo-07", ".5,"): ".5?", ("vo-07", ".7,"): ".7."}
MAX_WORDS = 3

timing = json.loads((P / "assets/vo/timing.json").read_text())
words = [w for w in timing["words"] if w["line"] not in SKIP]

# Merge split tokens: "65" ".7", "90" "%", "K" "3" ".1" → "K3.1".
merged = []
for w in words:
    t = PUNCT.get((w["line"], w["text"]), FIX.get(w["text"], w["text"]))
    prev = merged[-1] if merged and merged[-1]["line"] == w["line"] else None
    if prev and (t[0] in ".,%-" or (prev["text"] == "K" and t[0].isdigit())):
        prev["text"] += t
        prev["end"] = w["end"]
    else:
        merged.append({**w, "text": t})

groups, cur = [], []
for i, w in enumerate(merged):
    cur.append(w)
    nxt = merged[i + 1] if i + 1 < len(merged) else None
    if (len(cur) >= MAX_WORDS or re.search(r"[.,?!]$", w["text"]) or nxt is None
            or nxt["line"] != w["line"] or nxt["start"] - w["end"] >= 0.15):
        groups.append(cur)
        cur = []

html_groups, js = [], []
for gi, g in enumerate(groups):
    start = round(g[0]["start"] - 0.04, 3)
    nxt_start = groups[gi + 1][0]["start"] - 0.04 if gi + 1 < len(groups) else 999
    end = round(min(g[-1]["end"] + 0.3, nxt_start), 3)
    spans = " ".join(f'<span id="cw{gi}-{wi}">{w["text"].rstrip(",")}</span>' for wi, w in enumerate(g))
    html_groups.append(f'    <div id="cg{gi}" class="cap-g">{spans}</div>')
    js.append(f"      group({gi}, {start}, {end}, {json.dumps([round(w['start'], 3) for w in g])});")

out = f"""<template>
  <style>
    @font-face {{ font-family: "Bricolage Grotesque"; font-weight: 200 800; font-stretch: 75% 100%; font-display: block; src: url("assets/fonts/BricolageGrotesque.woff2") format("woff2"); }}
    #root {{ position: absolute; inset: 0; pointer-events: none; }}
    .cap-g {{ position: absolute; left: 0; top: 1236px; width: 1080px; text-align: center; overflow: visible; opacity: 0;
      font-family: "Bricolage Grotesque", sans-serif; font-weight: 600; font-size: 62px; line-height: 1.1; letter-spacing: -0.02em;
      color: rgba(244, 242, 238, 0.5); text-shadow: 0 2px 14px rgba(0, 0, 0, 0.6); white-space: nowrap; }}
  </style>
  <!-- Generated by scripts/build_captions.py — edit the script, not this file. -->
  <div id="root" data-composition-id="captions" data-width="1080" data-height="1920">
{chr(10).join(html_groups)}
  </div>
  <script>
    (() => {{
      const tl = gsap.timeline({{ paused: true }});
      const group = (i, start, end, wordStarts) => {{
        const g = `#cg${{i}}`;
        tl.fromTo(g, {{ opacity: 0 }}, {{ opacity: 1, duration: 0.06 }}, start);
        wordStarts.forEach((t, w) => {{
          tl.fromTo(`#cw${{i}}-${{w}}`, {{ color: "rgba(244, 242, 238, 0.5)" }}, {{ color: "#f4f2ee", duration: 0.05 }}, t);
        }});
        tl.to(g, {{ opacity: 0, duration: 0.06 }}, end - 0.06);
        tl.set(g, {{ opacity: 0, visibility: "hidden" }}, end);
      }};
{chr(10).join(js)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
(P / "compositions/captions.html").write_text(out)
print(len(groups), "caption groups")
for g in groups:
    print(round(g[0]["start"], 2), " ".join(w["text"] for w in g))
